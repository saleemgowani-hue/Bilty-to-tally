"""
Licence keys for the Freight Bilty-to-Tally Agent.

Keys are generated by SN Softech Solutions and validated by the app
**offline** — there is no licence server to call.

    SNBT-YKPQ-3W7M-XZ2N-8HJD
    ^^^^ ^                ^^^^^^
    |    |                signature (6 chars)
    |    plan: Y yearly, M monthly, T trial
    fixed prefix

The signature is an HMAC over the payload using LICENSE_SIGNING_SECRET.
Anyone can *check* a key with the same secret, but cannot mint a valid
one without it.

A key is single-use: the first company to activate it binds it.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import hmac
import secrets
from dataclasses import dataclass
from typing import Iterable, List, Optional

from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from database.models import Company, License
from utils.config import settings
from utils.logging import get_logger

log = get_logger("license")

ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"

PREFIX = "SNBT"
PAYLOAD_LEN = 10
SIGNATURE_LEN = 6
RAW_LEN = PAYLOAD_LEN + SIGNATURE_LEN

PLANS = {
    "Y": ("YEARLY", 365, "Yearly licence"),
    "M": ("MONTHLY", 30, "Monthly licence"),
    "T": ("TRIAL", 14, "Trial licence"),
}
PLAN_CHARS = {name: char for char, (name, _, _) in PLANS.items()}

CONFUSABLES = {"I": "1", "L": "1", "O": "0", "U": "V"}


class LicenseError(Exception):
    pass


@dataclass
class KeyInfo:
    key: str
    plan: str
    duration_days: int
    label: str


def normalize(key: str) -> str:
    cleaned = "".join(ch for ch in (key or "").upper() if ch.isalnum())
    if cleaned.startswith(PREFIX):
        cleaned = cleaned[len(PREFIX):]
    return "".join(CONFUSABLES.get(ch, ch) for ch in cleaned)


def format_key(raw: str) -> str:
    groups = [raw[i:i + 4] for i in range(0, len(raw), 4)]
    return "-".join([PREFIX] + groups)


def mask_key(key: str) -> str:
    raw = normalize(key)
    if len(raw) != RAW_LEN:
        return "••••"
    return f"{PREFIX}-{raw[:4]}-••••-••••-{raw[-4:]}"


def key_hash(key: str) -> str:
    return hashlib.sha256(normalize(key).encode()).hexdigest()


SECRET_MISSING_MESSAGE = (
    "This installation has no licence signing secret. Set "
    "LICENSE_SIGNING_SECRET in the .env file to the value supplied by "
    f"{settings.COMPANY_BRAND} ({settings.SUPPORT_CONTACT}), then restart."
)


def secret_problem() -> Optional[str]:
    secret = settings.LICENSE_SIGNING_SECRET
    if not secret:
        return SECRET_MISSING_MESSAGE
    if len(secret) < settings.LICENSE_SECRET_MIN_LENGTH:
        return (
            "The licence signing secret is too short to be safe "
            f"(needs at least {settings.LICENSE_SECRET_MIN_LENGTH} characters)."
        )
    return None


def _signature(payload: str) -> str:
    problem = secret_problem()
    if problem:
        raise LicenseError(problem)
    digest = hmac.new(
        settings.LICENSE_SIGNING_SECRET.encode(), payload.encode(), hashlib.sha256
    ).digest()
    out = []
    for byte in digest[:SIGNATURE_LEN]:
        out.append(ALPHABET[byte % len(ALPHABET)])
    return "".join(out)




def inspect_key(key: str) -> KeyInfo:
    raw = normalize(key)
    if not raw:
        raise LicenseError("Enter your licence key.")
    if len(raw) != RAW_LEN:
        raise LicenseError(
            f"That key is {len(raw)} characters long — a licence key has {RAW_LEN}. "
            "Check for a missing or extra character."
        )
    bad = [ch for ch in raw if ch not in ALPHABET]
    if bad:
        raise LicenseError(f"'{bad[0]}' is not a valid character in a licence key.")

    payload, signature = raw[:PAYLOAD_LEN], raw[PAYLOAD_LEN:]
    if not hmac.compare_digest(signature, _signature(payload)):
        raise LicenseError(
            "This licence key is not valid. Please check it and try again, or "
            f"contact {settings.COMPANY_BRAND} on {settings.SUPPORT_CONTACT}."
        )

    plan_char = payload[0]
    if plan_char not in PLANS:
        raise LicenseError("This licence key is not valid for this product.")

    plan, days, label = PLANS[plan_char]
    return KeyInfo(key=format_key(raw), plan=plan, duration_days=days, label=label)


def _aware(moment: Optional[dt.datetime]) -> Optional[dt.datetime]:
    if moment is None:
        return None
    return moment if moment.tzinfo else moment.replace(tzinfo=dt.timezone.utc)


def find_license(session: Session, key: str) -> Optional[License]:
    return (
        session.query(License)
        .filter(License.key_hash == key_hash(key))
        .one_or_none()
    )


def check_available(session: Session, key: str) -> KeyInfo:
    info = inspect_key(key)
    existing = find_license(session, key)
    if existing is not None:
        company = (
            session.query(Company).filter(Company.id == existing.company_id).one_or_none()
        )
        where = f" (activated by {company.name})" if company else ""
        raise LicenseError(
            f"This licence key has already been used{where}. Each key activates "
            "one company. Contact SN Softech Solutions for another key."
        )
    return info


def activate(
    session: Session,
    company: Company,
    key: str,
    *,
    activated_by: Optional[int] = None,
) -> License:
    info = check_available(session, key)
    now = dt.datetime.now(dt.timezone.utc)

    current = _aware(company.license_expires_at)
    start = current if (current and current > now) else now
    expires = start + dt.timedelta(days=info.duration_days)

    record = License(
        key_hash=key_hash(key),
        key_display=mask_key(key),
        plan=info.plan,
        company_id=company.id,
        activated_at=now,
        expires_at=expires,
        activated_by=activated_by,
    )
    session.add(record)

    company.license_plan = info.plan
    company.license_expires_at = expires
    company.license_key_display = mask_key(key)

    try:
        session.commit()
    except IntegrityError:
        session.rollback()
        raise LicenseError(
            "This licence key was activated a moment ago by someone else."
        )

    log.info("Licence %s activated for company %s until %s", info.plan, company.id, expires.date())
    return record


@dataclass
class LicenseStatus:
    plan: str
    expires_at: Optional[dt.datetime]
    days_left: int
    is_valid: bool
    is_expiring_soon: bool
    message: str


def status(company: Optional[Company]) -> LicenseStatus:
    if company is None:
        return LicenseStatus("NONE", None, 0, False, False, "No company loaded.")

    expires = _aware(company.license_expires_at)
    plan = company.license_plan or "NONE"

    if expires is None:
        return LicenseStatus(
            plan, None, 0, False, False,
            "No licence is active. Enter a licence key in Settings to continue.",
        )

    now = dt.datetime.now(dt.timezone.utc)
    days_left = (expires - now).days
    if expires <= now:
        return LicenseStatus(
            plan, expires, 0, False, False,
            f"Your {plan.lower()} licence expired on {expires.strftime('%d %b %Y')}. "
            f"Contact {settings.COMPANY_BRAND} on {settings.SUPPORT_CONTACT} to renew.",
        )

    soon = days_left <= settings.LICENSE_WARN_DAYS
    return LicenseStatus(
        plan, expires, days_left, True, soon,
        f"{plan.title()} licence — {days_left} day{'s' if days_left != 1 else ''} "
        f"remaining (expires {expires.strftime('%d %b %Y')}).",
    )


def company_licenses(session: Session, company_id: int) -> Iterable[License]:
    return (
        session.query(License)
        .filter(License.company_id == company_id)
        .order_by(License.activated_at.desc())
        .all()
    )
